static void relay_write(const RelayCh *r, uint8_t on)
{
#if RELAY_ACTIVE_LOW
    HAL_GPIO_WritePin(r->port, r->pin, on ? GPIO_PIN_RESET : GPIO_PIN_SET);
#else
    HAL_GPIO_WritePin(r->port, r->pin, on ? GPIO_PIN_SET : GPIO_PIN_RESET);
#endif
}
static void relay_all_off(void)
{
    for (uint32_t i = 0; i < RELAY_COUNT; i++) relay_write(&relays[i], 0);
}
static void servo_set_us(uint32_t channel, uint16_t pulse_us)
{
    __HAL_TIM_SET_COMPARE(&htim1, channel, pulse_us);
}
static void servo_start_all(void)
{
    for (uint32_t i = 0; i < SERVO_COUNT; i++) {
        HAL_TIM_PWM_Start(&htim1, servos[i].channel);
        servo_set_us(servos[i].channel, SERVO_0_DEG);
    }
}
